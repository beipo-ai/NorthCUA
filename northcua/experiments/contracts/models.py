class ExperimentAppProfile(str, Enum):
    """Built-in app profiles shipped with the golden E2E demo."""

    CHROME = "chrome"
    CALC = "calc"
    GIMP = "gimp"


class SandboxFileInjectionSpec(BaseModel):
    """A file that the experiment materializer stages into every task sandbox.

    Attributes:
        source_path: Existing host file to upload. Relative paths are resolved
            from the experiment spec file's parent directory by the loader.
        generated_name: Name of a fixture generated by the selected app profile.
        remote_path: Absolute destination path inside the sandbox.
        mode: Optional chmod mode, for example ``"0644"``.
        sha256: Optional checksum filled by materialization for generated files.
    """

    source_path: Path | None = None
    generated_name: str = ""
    remote_path: str
    mode: str = ""
    sha256: str = ""

    @model_validator(mode="after")
    def _validate_source(self) -> "SandboxFileInjectionSpec":
        """Ensure exactly one source form and an absolute remote path are set."""

        if bool(self.source_path) == bool(self.generated_name):
            raise ValueError("sandbox file injection requires exactly one source_path or generated_name")
        if not self.remote_path.startswith("/"):
            raise ValueError("sandbox file injection remote_path must be absolute")
        return self


class TraceExpectationSpec(BaseModel):
    """Artifact assertions required for a golden task to count as successful.

    Attributes:
        require_main_steps: Require a non-empty main-agent ``steps.jsonl``.
        require_main_llm_trace: Require a non-empty main-agent ``llm_trace.jsonl``.
        require_screenshot: Require at least one screenshot-like artifact.
        require_evaluator_report: Require evaluator ``final_report.json``.
        require_evaluator_llm_trace: Require evaluator ``llm_trace.jsonl``.
        evaluator_kind: Evaluator artifact directory name to search first.
    """

    require_main_steps: bool = True
    require_main_llm_trace: bool = True
    require_screenshot: bool = True
    require_evaluator_report: bool = True
    require_evaluator_llm_trace: bool = True
    evaluator_kind: str = "desktop_round_completion"


class ExperimentRuntimeMode(str, Enum):
    """How NorthCUA runtime code reaches a live experiment sandbox."""

    UPLOAD_WHEELS = "upload_wheels"
    BAKED_IN = "baked_in"


class ExperimentRuntimeSpec(BaseModel):
    """Runtime delivery policy for low-code experiment suites.

    ``upload_wheels`` preserves the historical developer behavior where a live
    experiment uploads freshly built wheels before each task. Production E2B
    suites that must prove a template is self-contained should set
    ``baked_in`` so stale templates cannot be silently masked by local wheels.
    """

    mode: ExperimentRuntimeMode = ExperimentRuntimeMode.UPLOAD_WHEELS


class ExperimentControllerSpec(BaseModel):
    """Controller settings used by a real or fake experiment run.

    Attributes:
        managed_local: Whether the suite should start a local controller
            subprocess before submitting batch tasks.
        local_host: Local controller bind host.
        local_port: Local controller bind port.
        public_url: Public ``ws://`` or ``wss://`` URL reachable by E2B.
        token: Shared controller token used for both device and submitter
            traffic in the golden v1 topology.
        db_path: Optional controller SQLite path.
        blob_dir: Optional controller blob/artifact directory.
        artifact_root_dir: Optional controller-owned main-agent artifact root.
        app_config_path: NorthCUA app config passed to controller runner plugins.
        executor_mode: Controller task executor mode.
        parallelism: One-knob process-executor parallelism; fills unset runner
            worker and queue limits when the managed controller starts.
        runner_workers: Maximum concurrent process-executor workers.
        worker_queue_max: Maximum process-executor scheduled/queued tasks.
        worker_start_timeout_seconds: Seconds allowed for a worker to connect.
        worker_heartbeat_timeout_seconds: Seconds without heartbeat before
            failing a process worker.
        process_worker_module: Optional process worker entrypoint override for
            no-LLM simulation and development diagnostics.
        insecure_dev_no_auth: Whether to disable auth for local development.
        startup_timeout_seconds: Time allowed for a managed controller to boot.
        command_timeout_floor_seconds: Minimum descriptor-backed command timeout
            for managed controller runs. Real E2B runs often traverse a public
            tunnel, so the controller should not treat a short descriptor budget
            as the full result-delivery budget.
    """

    managed_local: bool = True
    local_host: str = "127.0.0.1"
    local_port: int = 8885
    public_url: str = ""
    token: str = ""
    db_path: Path | None = None
    blob_dir: Path | None = None
    artifact_root_dir: Path | None = None
    app_config_path: Path = Path("config/app.local.yaml")
    executor_mode: Literal["in_process", "process"] = "in_process"
    parallelism: int = Field(default=0, ge=0)
    runner_workers: int = 0
    worker_queue_max: int = 0
    worker_start_timeout_seconds: float = 0.0
    worker_heartbeat_timeout_seconds: float = 0.0
    process_worker_module: str = ""
    insecure_dev_no_auth: bool = False
    startup_timeout_seconds: float = 20.0
    command_timeout_floor_seconds: float = 60.0


class ExperimentTaskSpec(BaseModel):
    """One app-level task in an experiment suite.

    Attributes:
        task_id: Stable task id used in batch, sandbox, and dataset outputs.
        app_profile: Built-in app fixture/profile used to prepare the sandbox.
        agent_kind: AgentKit agent kind; golden v1 uses ``desktop``.
        query: User-facing task text submitted to the main agent.
        max_steps: Maximum main-agent steps for one round/query.
        max_session_steps: Optional cumulative session step cap. ``0`` leaves
            the session-level budget disabled.
        fixtures: Files uploaded before task startup commands.
        startup_commands: Commands appended after fixture upload.
        timeout_seconds: Controller wait timeout for this task.
        max_retries: Whole-task retry budget for retryable transient failures.
        required_capabilities: Extra device capabilities required by this task.
        metadata: Extra small JSON metadata copied into the batch task.
    """

    task_id: str
    app_profile: ExperimentAppProfile
    agent_kind: str = "desktop"
    query: str
    max_steps: int = 100
    max_session_steps: int = 0
    fixtures: list[SandboxFileInjectionSpec] = Field(default_factory=list)
    startup_commands: list[SandboxCommandSpec] = Field(default_factory=list)
    timeout_seconds: float = 900.0
    max_retries: int = Field(default=0, ge=0)
    required_capabilities: set[Capability] = Field(default_factory=set)
    metadata: JsonObject = Field(default_factory=dict)


class ExperimentSpec(BaseModel):
    """Root experiment suite definition.

    Attributes:
        version: Experiment schema version.
        experiment_id: Stable output namespace.
        description: Human-readable suite purpose.
        controller: Controller process and public URL settings.
        sandbox: Default sandbox allocation for all tasks.
        runtime: Runtime dependency delivery policy.
        concurrency: Maximum concurrent batch tasks.
        trace_expectations: Artifact assertions applied to every task.
        tasks: Ordered app-level tasks.
        metadata: Small suite metadata copied into reports.
    """

    version: str = "v1"
    experiment_id: str = Field(default_factory=lambda: f"experiment-{uuid.uuid4().hex[:12]}")
    description: str = ""
    controller: ExperimentControllerSpec = Field(default_factory=ExperimentControllerSpec)
    sandbox: SandboxProviderSpec = Field(default_factory=SandboxProviderSpec)
    runtime: ExperimentRuntimeSpec = Field(default_factory=ExperimentRuntimeSpec)
    concurrency: int = 3
    trace_expectations: TraceExpectationSpec = Field(default_factory=TraceExpectationSpec)
    tasks: list[ExperimentTaskSpec]
    metadata: JsonObject = Field(default_factory=dict)

    @model_validator(mode="after")
    def _validate_tasks(self) -> "ExperimentSpec":
        """Ensure the suite has unique task ids."""

        if not self.tasks:
            raise ValueError("experiment requires at least one task")
        seen: set[str] = set()
        duplicates: set[str] = set()
        for task in self.tasks:
            if task.task_id in seen:
                duplicates.add(task.task_id)
            seen.add(task.task_id)
        if duplicates:
            raise ValueError(f"experiment task_id values must be unique: {sorted(duplicates)}")
        return self


class ExperimentRunConfig(BaseModel):
    """Runtime options for executing an experiment spec.

    Attributes:
        spec: Validated experiment suite.
        output_dir: Root directory for experiment, batch, and report artifacts.
        public_controller_url: CLI override for ``spec.controller.public_url``.
        dry_run: Validate and project manifests without creating sandboxes.
        require_real_e2b: Whether to require the E2B live-run environment flag.
    """

    spec: ExperimentSpec
    output_dir: Path = Path("logs/experiments")
    public_controller_url: str = ""
    dry_run: bool = False
    require_real_e2b: bool = True


class ExperimentTaskResult(BaseModel):
    """Dataset-oriented result row for one experiment task.

    Attributes:
        task_id: Experiment task id.
        app_profile: App profile name.
        status: Batch task status.
        controller_task_id: Controller task id.
        trace_id: Controller trace id.
        session_id: Controller session id.
        sandbox_id: Provider sandbox id.
        query: Submitted task text.
        fixture_remote_paths: Remote fixture paths injected for this task.
        fixture_sha256: Source fixture checksums keyed by remote path.
        main_trace_dir: Main-agent session trace directory when found.
        main_steps_path: Path to main-agent ``steps.jsonl`` when found.
        main_llm_trace_path: Path to main-agent ``llm_trace.jsonl`` when found.
        screenshot_paths: Screenshot artifacts found for the task/session.
        evaluator_trace_dir: Evaluator trace/report directory when found.
        evaluator_report_path: Evaluator final report path when found.
        evaluator_evidence_manifest_path: Evaluator evidence manifest path when found.
        evaluator_llm_trace_path: Evaluator LLM trace path when found.
        evaluator_verdict: Parsed evaluator ``overall_verdict``.
        evaluator_safety_risk_level: Parsed evaluator safety risk level.
        evaluator_efficiency_rating: Parsed evaluator efficiency rating.
        evaluator_diagnosis_category_breakdown: Counts by evaluator diagnosis
            category for this task.
        passed: Whether all configured trace expectations passed.
        errors: Missing artifacts or failed assertions.
    """

    task_id: str
    app_profile: ExperimentAppProfile
    status: str
    controller_task_id: str = ""
    trace_id: str = ""
    session_id: str = ""
    sandbox_id: str = ""
    query: str = ""
    fixture_remote_paths: list[str] = Field(default_factory=list)
    fixture_sha256: dict[str, str] = Field(default_factory=dict)
    main_trace_dir: str = ""
    main_steps_path: str = ""
    main_llm_trace_path: str = ""
    screenshot_paths: list[str] = Field(default_factory=list)
    evaluator_trace_dir: str = ""
    evaluator_report_path: str = ""
    evaluator_evidence_manifest_path: str = ""
    evaluator_llm_trace_path: str = ""
    evaluator_verdict: str = ""
    evaluator_safety_risk_level: str = ""
    evaluator_efficiency_rating: int = 0
    evaluator_diagnosis_category_breakdown: dict[str, int] = Field(default_factory=dict)
    passed: bool = False
    errors: list[str] = Field(default_factory=list)


