"""Agent-specific request adapters for batch task planning."""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass, field
from typing import Protocol

from northcua.batch.contracts import BatchTaskSpec
from northcua.submitter.specs import DesktopSubmitSpec, SubmitTaskPayload, WebSubmitSpec


class BatchAgentRequestAdapter(Protocol):
    """Project one manifest task into a controller submitter payload."""

    @property
    def agent_kinds(self) -> frozenset[str]:
        """Return agent kind aliases handled by this adapter.

        Returns:
            Canonical agent kind and any legacy aliases accepted in manifests.
        """
        ...

    def can_project(self, task: BatchTaskSpec) -> bool:
        """Return whether this adapter can project ``task``.

        Args:
            task: Manifest task candidate.

        Returns:
            ``True`` when ``project`` can build a submitter payload.
        """
        ...

    def project(self, task: BatchTaskSpec) -> SubmitTaskPayload:
        """Build a controller submitter payload from ``task``.

        Args:
            task: Manifest task to project.

        Returns:
            Submitter payload with agent-specific request metadata.
        """
        ...


@dataclass(slots=True)
class BatchRequestAdapterRegistry:
    """Registry of batch request adapters keyed by AgentKit agent kind.

    Attributes:
        adapters: Ordered adapter list. Earlier adapters take precedence when
            two adapters claim the same agent kind.
    """

    adapters: list[BatchAgentRequestAdapter] = field(default_factory=list)

    def register(self, adapter: BatchAgentRequestAdapter) -> None:
        """Register one request adapter.

        Args:
            adapter: Adapter to append to lookup order.
        """

        self.adapters.append(adapter)

    def project(self, task: BatchTaskSpec) -> SubmitTaskPayload | None:
        """Project a task through the first compatible adapter.

        Args:
            task: Manifest task to project.

        Returns:
            Submitter payload, or ``None`` when no adapter handles the task.
        """

        for adapter in self.adapters:
            if task.agent_kind in adapter.agent_kinds and adapter.can_project(task):
                return adapter.project(task)
        return None


class DesktopBatchRequestAdapter:
    """Project desktop batch aliases into ``DesktopSubmitSpec``."""

    agent_kinds = frozenset({"desktop"})

    def can_project(self, task: BatchTaskSpec) -> bool:
        """Return whether this is a desktop task.

        Args:
            task: Manifest task candidate.

        Returns:
            ``True`` when the task should be submitted through desktop remote.
        """

        return task.agent_kind in self.agent_kinds

    def project(self, task: BatchTaskSpec) -> SubmitTaskPayload:
        """Build a desktop submit payload.

        Args:
            task: Manifest task containing the desktop query and optional step
                limit.

        Returns:
            Controller submit payload generated by ``DesktopSubmitSpec``.
        """

        spec = DesktopSubmitSpec(
            query=task.request,
            max_steps=task.max_steps or 12,
            max_session_steps=task.max_session_steps,
        )
        if task.required_capabilities:
            spec.required_capabilities = set(task.required_capabilities)
        return spec.submit_payload()


class WebBatchRequestAdapter:
    """Project generic web batch aliases into ``WebSubmitSpec``."""

    agent_kinds = frozenset({"web"})

    def can_project(self, task: BatchTaskSpec) -> bool:
        """Return whether this is a generic web task.

        Args:
            task: Manifest task candidate.

        Returns:
            ``True`` when the task should be submitted through the generic web
            agent.
        """

        return task.agent_kind in self.agent_kinds

    def project(self, task: BatchTaskSpec) -> SubmitTaskPayload:
        """Build a web-agent submit payload.

        Args:
            task: Manifest task containing the query, optional URL, and step
                limit.

        Returns:
            Controller submit payload generated by ``WebSubmitSpec``.
        """

        raw_headed = task.metadata.get("headed")
        headed = raw_headed if isinstance(raw_headed, bool) else None
        spec = WebSubmitSpec(
            query=task.request,
            url=task.url,
            headed=headed,
            max_steps=task.max_steps,
            max_session_steps=task.max_session_steps,
        )
        if task.required_capabilities:
            spec.required_capabilities = set(task.required_capabilities)
        return spec.submit_payload()


def default_batch_request_adapter_registry(
    extra_adapters: Iterable[BatchAgentRequestAdapter] = (),
) -> BatchRequestAdapterRegistry:
    """Build the default adapter registry used by the batch planner.

    Args:
        extra_adapters: Optional caller-provided adapters appended after the
            built-in desktop/web adapters.

    Returns:
        Registry ready for ``BatchTaskPlanner``.
    """

    registry = BatchRequestAdapterRegistry(
        [
            DesktopBatchRequestAdapter(),
            WebBatchRequestAdapter(),
        ]
    )
    for adapter in extra_adapters:
        registry.register(adapter)
    return registry
